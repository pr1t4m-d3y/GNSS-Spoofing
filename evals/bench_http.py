"""End-to-end HTTP latency against a running API. Writes evals/results/HTTP.md.

Usage: ``python evals/bench_http.py --base-url https://<service-url>``

Works against a local server or a deployed Cloud Run service. The API key, if the service
needs one, is read from the environment variable named by ``--api-key-env`` (default
``GNSS_API_KEY``) and is never written to the report.

The first request is timed on its own: when the service had been idle with scale to zero,
that request includes the cold start. Every later number is warm.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import platform
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

import numpy as np
import pandas as pd


def send(
    url: str, body: bytes | None, headers: dict[str, str], timeout: float
) -> tuple[int, float]:
    """One request. Returns ``(status, seconds)``; status 0 means the request failed to complete."""
    request = urllib.request.Request(url, data=body, headers=headers)
    started = time.perf_counter()
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            response.read()
            status = response.status
    except urllib.error.HTTPError as error:
        status = error.code
    except (urllib.error.URLError, TimeoutError, OSError):
        status = 0
    return status, time.perf_counter() - started


def percentiles(seconds: list[float]) -> dict[str, float]:
    values = np.asarray(seconds) * 1000.0
    return {
        "p50_ms": float(np.percentile(values, 50)),
        "p95_ms": float(np.percentile(values, 95)),
        "p99_ms": float(np.percentile(values, 99)),
    }


def load_rows(sample: Path, count: int) -> list[dict[str, Any]]:
    frame = pd.read_csv(sample)
    repeats = -(-count // len(frame))
    frame = pd.concat([frame] * repeats, ignore_index=True).head(count)
    return list(json.loads(frame.to_json(orient="records")))


def run(args: argparse.Namespace) -> dict[str, Any]:
    base = args.base_url.rstrip("/")
    headers = {"Content-Type": "application/json"}
    key = os.environ.get(args.api_key_env)
    if key:
        headers["X-API-Key"] = key

    first_status, first_seconds = send(f"{base}/ready", None, {}, args.timeout)

    batches: list[dict[str, Any]] = []
    for size in args.batch_sizes:
        body = json.dumps({"data": load_rows(args.sample, size)}).encode()
        for _ in range(args.warmup):
            send(f"{base}/predict/batch", body, headers, args.timeout)
        for concurrency in args.concurrency:
            started = time.perf_counter()
            with ThreadPoolExecutor(max_workers=concurrency) as pool:
                results = list(
                    pool.map(
                        lambda _: send(f"{base}/predict/batch", body, headers, args.timeout),
                        range(args.requests),
                    )
                )
            wall = time.perf_counter() - started
            ok = [seconds for status, seconds in results if status == 200]
            entry: dict[str, Any] = {
                "batch_rows": size,
                "concurrency": concurrency,
                "requests": args.requests,
                "failed": args.requests - len(ok),
                "requests_per_second": len(ok) / wall,
                "rows_per_second": len(ok) * size / wall,
            }
            if ok:
                entry.update(percentiles(ok))
            batches.append(entry)

    return {
        "generated_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "client": {"platform": platform.platform(), "python": platform.python_version()},
        "target": urlparse(base).netloc,
        "authenticated": bool(key),
        "first_request": {"status": first_status, "ms": first_seconds * 1000.0},
        "sample": str(args.sample),
        "warmup": args.warmup,
        "batches": batches,
    }


def render(result: dict[str, Any]) -> str:
    first = result["first_request"]
    lines = [
        "# End-to-end HTTP latency",
        "",
        "Generated by `python evals/bench_http.py`. Do not edit by hand.",
        "",
        f"Generated (UTC): {result['generated_utc']}",
        "",
        f"Target: `{result['target']}`. Client: {result['client']['platform']}, "
        f"Python {result['client']['python']}. API key sent: {'yes' if result['authenticated'] else 'no'}.",
        "",
        "Times include the network path between this client and the target, TLS, JSON "
        "encoding, validation, feature engineering and scoring.",
        "",
        "## First request",
        "",
        f"`GET /ready` answered {first['status']} in {first['ms']:.0f} ms. If the service had "
        "scaled to zero before this request, that figure includes the cold start; otherwise it "
        "is a warm request.",
        "",
        "## `POST /predict/batch`",
        "",
        f"{result['warmup']} warm-up request(s) per batch size, then the requests below.",
        "",
        "| Rows per request | Concurrency | Requests | Failed | p50 ms | p95 ms | p99 ms | Requests/s | Rows/s |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for entry in result["batches"]:
        if "p50_ms" in entry:
            timings = f"{entry['p50_ms']:.1f} | {entry['p95_ms']:.1f} | {entry['p99_ms']:.1f}"
        else:
            timings = "n/a | n/a | n/a"
        lines.append(
            f"| {entry['batch_rows']} | {entry['concurrency']} | {entry['requests']} | "
            f"{entry['failed']} | {timings} | {entry['requests_per_second']:.1f} | "
            f"{entry['rows_per_second']:,.0f} |"
        )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default="http://localhost:8000")
    parser.add_argument("--api-key-env", default="GNSS_API_KEY")
    parser.add_argument("--sample", type=Path, default=Path("examples/mixed_signals_500.csv"))
    parser.add_argument("--batch-sizes", type=int, nargs="+", default=[1, 100, 500])
    parser.add_argument("--concurrency", type=int, nargs="+", default=[1, 4])
    parser.add_argument("--requests", type=int, default=50)
    parser.add_argument("--warmup", type=int, default=3)
    parser.add_argument("--timeout", type=float, default=60.0)
    parser.add_argument("--out-dir", type=Path, default=Path("evals/results"))
    args = parser.parse_args(argv)

    result = run(args)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "http.json").write_text(json.dumps(result, indent=2) + "\n")
    (args.out_dir / "HTTP.md").write_text(render(result))
    print(f"Wrote {args.out_dir / 'HTTP.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
