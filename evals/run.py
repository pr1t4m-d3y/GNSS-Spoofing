"""Reproducible evaluation. Writes evals/results/RESULTS.md and results.json.

Usage: ``python evals/run.py`` (from the repository root).

Protocol: fit the Isolation Forest on the first 70% of every channel's timeline
(genuine rows only), then score the remaining 30% after injecting synthetic attacks
into it. See ``gnss_shield.evaluation`` for the recipe and its limits.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import platform
import sys
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import sklearn

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from gnss_shield.data import (  # noqa: E402
    clean_gnss,
    dataset_summary,
    genuine_only,
    load_training_sheet,
)
from gnss_shield.evaluation import (  # noqa: E402
    ATTACK_RECIPE,
    evaluate_frame,
    inject_scattered,
    inject_sustained,
    temporal_split,
)
from gnss_shield.features import (  # noqa: E402
    ALL_MODEL_FEATURES,
    REQUIRED_COLUMNS,
    ROLLING_WINDOW,
    engineer_features,
    feature_matrix,
)
from gnss_shield.model import (  # noqa: E402
    DEFAULT_CONTAMINATION,
    DEFAULT_N_ESTIMATORS,
    DEFAULT_SEED,
    build_pipeline,
)

METRICS = ("precision", "recall", "f1", "roc_auc", "average_precision")


def _fmt(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.4f}"


def _aggregate(runs: list[dict[str, Any]]) -> dict[str, dict[str, float | None]]:
    summary: dict[str, dict[str, float | None]] = {}
    for metric in METRICS:
        values = [r[metric] for r in runs if r[metric] is not None]
        summary[metric] = {
            "mean": float(np.mean(values)) if values else None,
            "std": float(np.std(values)) if values else None,
        }
    return summary


def run(args: argparse.Namespace) -> dict[str, Any]:
    raw = load_training_sheet(args.data)
    clean = genuine_only(clean_gnss(raw))
    summary = dataset_summary(raw, clean)

    train, test = temporal_split(clean, args.train_fraction)

    train_features = feature_matrix(engineer_features(train)).to_numpy(dtype=float)
    train_features = train_features[np.isfinite(train_features).all(axis=1)]
    pipeline = build_pipeline(random_state=DEFAULT_SEED)
    pipeline.fit(train_features)

    scenarios: dict[str, list[dict[str, Any]]] = {"scattered": [], "sustained": []}
    for seed in args.seeds:
        rng = np.random.default_rng(seed)
        frame, labels = inject_scattered(test, args.scattered_rate, rng)
        scenarios["scattered"].append({"seed": seed, **evaluate_frame(pipeline, frame, labels)})

        rng = np.random.default_rng(seed)
        frame, labels = inject_sustained(test, args.blocks, args.block_len, rng)
        scenarios["sustained"].append({"seed": seed, **evaluate_frame(pipeline, frame, labels)})

    # Genuine-only held-out rows: how often does the detector raise a false alarm?
    genuine_labels = np.zeros(len(test), dtype=int)
    genuine = evaluate_frame(pipeline, test, genuine_labels)

    return {
        "generated_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "environment": {
            "python": platform.python_version(),
            "scikit_learn": sklearn.__version__,
            "pandas": pd.__version__,
            "numpy": np.__version__,
        },
        "data": {"file": args.data.name, **summary},
        "features": {"raw_fields": len(REQUIRED_COLUMNS), "model_features": len(ALL_MODEL_FEATURES)},
        "split": {
            "method": "time-ordered, per channel",
            "train_fraction": args.train_fraction,
            "train_rows": int(len(train)),
            "test_rows": int(len(test)),
        },
        "model": {
            "type": "StandardScaler + IsolationForest",
            "n_estimators": DEFAULT_N_ESTIMATORS,
            "contamination": DEFAULT_CONTAMINATION,
            "random_state": DEFAULT_SEED,
            "rolling_window": ROLLING_WINDOW,
        },
        "attack_recipe": {k: list(v) for k, v in ATTACK_RECIPE.items()},
        "protocol": {
            "seeds": list(args.seeds),
            "scattered_rate": args.scattered_rate,
            "sustained_blocks": args.blocks,
            "sustained_block_len": args.block_len,
        },
        "scenarios": {
            name: {"aggregate": _aggregate(runs), "runs": runs} for name, runs in scenarios.items()
        },
        "genuine_only": genuine,
    }


def render(result: dict[str, Any]) -> str:
    env, data, split = result["environment"], result["data"], result["split"]
    model, proto = result["model"], result["protocol"]
    lines = [
        "# Evaluation results",
        "",
        "Generated by `python evals/run.py`. Do not edit by hand.",
        "",
        f"Generated (UTC): {result['generated_utc']}",
        "",
        "## Environment",
        "",
        f"Python {env['python']}, scikit-learn {env['scikit_learn']}, "
        f"pandas {env['pandas']}, numpy {env['numpy']}.",
        "",
        "## Data",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| File | `{data['file']}` |",
        f"| Raw rows | {data['raw_rows']:,} |",
        f"| Usable rows (genuine, tracked) | {data['usable_rows']:,} |",
        f"| Channels | {len(data['channels'])} ({', '.join(data['channels'])}) |",
        f"| Epochs | {data['epochs']:,} |",
        f"| Raw receiver fields used | {result['features']['raw_fields']} |",
        f"| Model features | {result['features']['model_features']} |",
        "",
        "## Method",
        "",
        f"* **Split:** {split['method']}. The first {split['train_fraction']:.0%} of each "
        f"channel's rows train the model ({split['train_rows']:,} rows); the remainder "
        f"({split['test_rows']:,} rows) is held out.",
        f"* **Model:** {model['type']} (n_estimators={model['n_estimators']}, "
        f"contamination={model['contamination']}, random_state={model['random_state']}). "
        "Trained on genuine rows only; no labels are used for training.",
        "* **Labels:** the training sheet contains no spoofed rows, so spoofed rows are "
        "synthesised. Labels are used only to score the detector.",
        "* **Attack recipe (added to a genuine row):** "
        + "; ".join(f"{k} +U({lo:g}, {hi:g})" for k, (lo, hi) in result["attack_recipe"].items())
        + ".",
        f"* **Scattered:** {proto['scattered_rate']:.0%} of held-out rows perturbed at random.",
        f"* **Sustained:** {proto['sustained_blocks']} contiguous blocks of "
        f"{proto['sustained_block_len']} rows, each inside one channel.",
        f"* **Seeds:** {', '.join(str(s) for s in proto['seeds'])}.",
        "* **Labelling convention:** row level. A rolling window spreads a perturbation over "
        f"about {model['rolling_window']} neighbouring rows, so neighbours of a perturbed row "
        "can be flagged and are counted as false positives.",
        "",
    ]
    for name in ("scattered", "sustained"):
        block = result["scenarios"][name]
        lines += [
            f"## {name.capitalize()} attacks",
            "",
            "| Metric | Mean | Std |",
            "|---|---|---|",
        ]
        for metric in METRICS:
            agg = block["aggregate"][metric]
            lines.append(f"| {metric} | {_fmt(agg['mean'])} | {_fmt(agg['std'])} |")
        lines += [
            "",
            "| Seed | Precision | Recall | F1 | TP | FP | FN | TN |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for run_ in block["runs"]:
            lines.append(
                f"| {run_['seed']} | {_fmt(run_['precision'])} | {_fmt(run_['recall'])} | "
                f"{_fmt(run_['f1'])} | {run_['tp']} | {run_['fp']} | {run_['fn']} | {run_['tn']} |"
            )
        lines.append("")
    genuine = result["genuine_only"]
    lines += [
        "## False alarms on genuine held-out data",
        "",
        f"No attacks injected: {genuine['fp']} of {genuine['rows']:,} held-out rows flagged "
        f"(rate {_fmt(genuine['flag_rate'])}).",
        "",
        "## Limits of this evaluation",
        "",
        "* Attacks are synthetic perturbations of genuine data, not recordings of real "
        "spoofers; the numbers do not predict performance against real attacks.",
        "* One recording and one split; no confidence intervals beyond the seed spread.",
        "* The decision threshold comes from the training-time `contamination` setting.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=Path("data/train.xls"))
    parser.add_argument("--out-dir", type=Path, default=Path("evals/results"))
    parser.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    parser.add_argument("--train-fraction", type=float, default=0.7)
    parser.add_argument("--scattered-rate", type=float, default=0.10)
    parser.add_argument("--blocks", type=int, default=5)
    parser.add_argument("--block-len", type=int, default=100)
    args = parser.parse_args(argv)

    result = run(args)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "results.json").write_text(json.dumps(result, indent=2) + "\n")
    (args.out_dir / "RESULTS.md").write_text(render(result))
    print(f"Wrote {args.out_dir / 'RESULTS.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
