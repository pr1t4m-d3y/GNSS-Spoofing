"""Deployment-readiness benchmark. Writes evals/results/EDGE.md and edge.json.

Usage: ``python evals/bench.py`` (from the repository root).

The measurement runs in a fresh worker process so peak memory covers only what the
detector needs: interpreter, libraries, the model and the batches scored. Latency is
measured for the model alone and for the full path (cleaning is excluded; feature
engineering and scoring are included). Single process, CPU only.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import platform
import resource
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from gnss_shield.data import clean_gnss  # noqa: E402
from gnss_shield.detector import load_detector  # noqa: E402
from gnss_shield.features import (  # noqa: E402
    REQUIRED_COLUMNS,
    engineer_features,
    feature_matrix,
)

TRACKING_LOOP_FIELDS = ("EC", "LC", "PC", "PIP", "PQP", "TCD")


def _peak_rss_mb() -> float:
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    # macOS reports bytes, Linux reports kilobytes.
    return peak / (1024 * 1024) if sys.platform == "darwin" else peak / 1024


def _percentiles(samples_ms: list[float]) -> dict[str, float]:
    values = np.asarray(samples_ms)
    return {
        "p50_ms": float(np.percentile(values, 50)),
        "p95_ms": float(np.percentile(values, 95)),
        "p99_ms": float(np.percentile(values, 99)),
    }


def _tile(frame: pd.DataFrame, rows: int) -> pd.DataFrame:
    repeats = -(-rows // len(frame))
    return pd.concat([frame] * repeats, ignore_index=True).head(rows).copy()


def worker(args: argparse.Namespace) -> dict[str, Any]:
    started = time.perf_counter()
    detector = load_detector(args.model)
    load_seconds = time.perf_counter() - started
    rss_after_load = _peak_rss_mb()

    sample = clean_gnss(pd.read_csv(args.sample))

    batches: list[dict[str, Any]] = []
    for size in args.batch_sizes:
        frame = _tile(sample, size)
        matrix = feature_matrix(engineer_features(frame)).to_numpy(dtype=float)

        for _ in range(args.warmup):
            detector.decision_function(matrix)
            detector.analyse(frame)

        model_ms: list[float] = []
        full_ms: list[float] = []
        for _ in range(args.runs):
            t0 = time.perf_counter()
            detector.decision_function(matrix)
            model_ms.append((time.perf_counter() - t0) * 1000)
            t0 = time.perf_counter()
            detector.analyse(frame)
            full_ms.append((time.perf_counter() - t0) * 1000)

        model_stats = _percentiles(model_ms)
        full_stats = _percentiles(full_ms)
        batches.append(
            {
                "batch_size": size,
                "model_only": {
                    **model_stats,
                    "rows_per_second": size / (model_stats["p50_ms"] / 1000),
                },
                "features_and_model": {
                    **full_stats,
                    "rows_per_second": size / (full_stats["p50_ms"] / 1000),
                },
            }
        )

    return {
        "load_seconds": load_seconds,
        "peak_rss_mb_after_load": rss_after_load,
        "peak_rss_mb_after_inference": _peak_rss_mb(),
        "batches": batches,
    }


def render(result: dict[str, Any]) -> str:
    host = result["host"]
    lines = [
        "# Deployment-readiness measurements",
        "",
        "Generated by `python evals/bench.py`. Do not edit by hand.",
        "",
        f"Generated (UTC): {result['generated_utc']}",
        "",
        "## Host",
        "",
        f"{host['platform']}, Python {host['python']}, {host['cpu_count']} logical CPUs. "
        "Single process, CPU only, one inference thread.",
        "",
        "## Footprint",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Model file | {result['model_bytes']:,} bytes ({result['model_bytes'] / 1e6:.2f} MB) |",
        f"| Model load time | {result['worker']['load_seconds'] * 1000:.1f} ms |",
        f"| Peak RSS after loading the model | {result['worker']['peak_rss_mb_after_load']:.0f} MB |",
        f"| Peak RSS after all batches | {result['worker']['peak_rss_mb_after_inference']:.0f} MB |",
        "",
        "Peak RSS is measured in a fresh worker process and includes the Python "
        "interpreter, pandas, numpy and scikit-learn.",
        "",
        "## Latency and throughput",
        "",
        f"{result['runs']} timed runs per row after {result['warmup']} warm-up runs; "
        f"input rows come from `{result['sample']}`.",
        "",
        "| Batch rows | Path | p50 ms | p95 ms | p99 ms | Rows per second (at p50) |",
        "|---|---|---|---|---|---|",
    ]
    for batch in result["worker"]["batches"]:
        for key, label in (("model_only", "model only"), ("features_and_model", "features + model")):
            stats = batch[key]
            lines.append(
                f"| {batch['batch_size']} | {label} | {stats['p50_ms']:.2f} | "
                f"{stats['p95_ms']:.2f} | {stats['p99_ms']:.2f} | {stats['rows_per_second']:,.0f} |"
            )
    lines += [
        "",
        "HTTP overhead, JSON encoding and network time are not included here.",
        "",
        "## Receiver fields required",
        "",
        "The detector needs these fields for every epoch and channel:",
        "",
        "| Field | Kind |",
        "|---|---|",
    ]
    for field in REQUIRED_COLUMNS:
        kind = "tracking-loop output" if field in TRACKING_LOOP_FIELDS else "observable"
        lines.append(f"| `{field}` | {kind} |")
    lines += [
        "",
        "Tracking-loop outputs (correlator and I/Q power values) are not part of NMEA or "
        "standard RINEX observation files; the receiver must expose them.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, default=Path("models/gnss_iforest.pkl"))
    parser.add_argument("--sample", type=Path, default=Path("examples/mixed_signals_500.csv"))
    parser.add_argument("--batch-sizes", type=int, nargs="+", default=[1, 100, 1000, 10000])
    parser.add_argument("--runs", type=int, default=50)
    parser.add_argument("--warmup", type=int, default=3)
    parser.add_argument("--out-dir", type=Path, default=Path("evals/results"))
    parser.add_argument("--worker", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    if args.worker:
        print(json.dumps(worker(args)))
        return 0

    command = [
        sys.executable,
        str(Path(__file__).resolve()),
        "--worker",
        "--model",
        str(args.model),
        "--sample",
        str(args.sample),
        "--runs",
        str(args.runs),
        "--warmup",
        str(args.warmup),
        "--batch-sizes",
        *[str(size) for size in args.batch_sizes],
    ]
    completed = subprocess.run(command, capture_output=True, text=True, check=True)
    result = {
        "generated_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "host": {
            "platform": platform.platform(),
            "python": platform.python_version(),
            "cpu_count": os.cpu_count(),
        },
        "model_bytes": args.model.stat().st_size,
        "sample": str(args.sample),
        "runs": args.runs,
        "warmup": args.warmup,
        "worker": json.loads(completed.stdout),
    }
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "edge.json").write_text(json.dumps(result, indent=2) + "\n")
    (args.out_dir / "EDGE.md").write_text(render(result))
    print(f"Wrote {args.out_dir / 'EDGE.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
