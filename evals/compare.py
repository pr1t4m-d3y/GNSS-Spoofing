"""Isolation Forest vs XGBoost on real labelled telemetry. Writes evals/results/COMPARE.md.

Usage: ``python evals/compare.py --data data/labelled/<file> [<file> ...]``

Each file is a telemetry sheet (.xls or .csv) with the usual columns plus a label column
where 0 means genuine and any other value marks a spoofed row (its value is reported as
the attack class). Every file is treated as its own recording: its channels are split by
time separately, and rolling windows never cross files.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import platform
import sys
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import sklearn
import xgboost

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from gnss_shield.comparison import compare_models  # noqa: E402
from gnss_shield.data import LABEL_COLUMN, clean_gnss, load_training_sheet  # noqa: E402

MODELS = (("isolation_forest", "Isolation Forest (unsupervised)"), ("xgboost", "XGBoost (supervised)"))


def _fmt(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.4f}"


def load_recordings(paths: list[Path], label_column: str) -> pd.DataFrame:
    """Read every file and give each recording its own channel namespace."""
    frames = []
    for path in paths:
        raw = load_training_sheet(path)
        if label_column != LABEL_COLUMN:
            raw = raw.rename(columns={label_column: LABEL_COLUMN})
        if LABEL_COLUMN not in raw.columns:
            raise ValueError(f"{path} has no label column {label_column!r}")
        if "channel" in raw.columns:
            raw["channel"] = path.stem + ":" + raw["channel"].astype(str)
        else:
            raw["channel"] = path.stem
        frames.append(raw)
    return pd.concat(frames, ignore_index=True)


def _metric_table(block: dict[str, Any]) -> list[str]:
    lines = [
        "| Model | Precision | Recall | F1 | ROC-AUC | Average precision | TP | FP | FN | TN |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for key, label in MODELS:
        m = block[key]
        lines.append(
            f"| {label} | {_fmt(m['precision'])} | {_fmt(m['recall'])} | {_fmt(m['f1'])} | "
            f"{_fmt(m['roc_auc'])} | {_fmt(m['average_precision'])} | "
            f"{m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} |"
        )
    return lines


def render(result: dict[str, Any], files: list[str]) -> str:
    splits = result["splits"]
    lines = [
        "# Isolation Forest vs XGBoost",
        "",
        "Generated by `python evals/compare.py`. Do not edit by hand.",
        "",
        f"Generated (UTC): {result['generated_utc']}",
        "",
        f"Python {result['environment']['python']}, scikit-learn {result['environment']['scikit_learn']}, "
        f"xgboost {result['environment']['xgboost']}, pandas {result['environment']['pandas']}, "
        f"numpy {result['environment']['numpy']}.",
        "",
        "## Method",
        "",
        f"* **Data:** {', '.join(f'`{name}`' for name in files)}; labels are real (0 = genuine, "
        "other values = attack class).",
        f"* **Split:** time-ordered per channel and per recording, first {splits['train_fraction']:.0%} "
        f"for training ({splits['train_rows']:,} rows), the rest held out ({splits['test_rows']:,} rows).",
        "* **Features:** the same 35 physics-informed features for both models.",
        "* **Isolation Forest:** fitted on the genuine training rows only; flags a row when its "
        "decision value is below 0.",
        "* **XGBoost:** fitted on all training rows with their labels (spoofed class re-weighted by the "
        "genuine-to-spoofed ratio); flags a row when its probability is at least 0.5.",
        f"* **Seed:** {result['seed']}. Row-level metrics; the spoofed class is the positive class.",
        "",
        "## Rows per class",
        "",
        "| Class | Train | Test |",
        "|---|---|---|",
    ]
    for cls in sorted(set(splits["train_classes"]) | set(splits["test_classes"]), key=int):
        lines.append(
            f"| {cls} | {splits['train_classes'].get(cls, 0):,} | {splits['test_classes'].get(cls, 0):,} |"
        )
    lines += ["", "## Overall (all attack classes together)", ""]
    lines += _metric_table(result["overall"])
    for cls, block in result["per_class"].items():
        lines += ["", f"## Genuine vs attack class {cls}", ""]
        lines += _metric_table(block)
    lines += [
        "",
        "## Most important XGBoost features",
        "",
        "| Feature | Importance |",
        "|---|---|",
    ]
    for item in result["xgboost_top_features"]:
        lines.append(f"| `{item['feature']}` | {item['importance']:.4f} |")
    lines += [
        "",
        "## Limits",
        "",
        "* One dataset and one split; no confidence intervals.",
        "* XGBoost sees attack labels at training time and the Isolation Forest does not, so the "
        "comparison measures what labels are worth, not which algorithm is better in general.",
        "* Neighbouring rows share rolling-window features, so rows near an attack boundary can be "
        "misclassified for either model.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, nargs="+", required=True)
    parser.add_argument("--label-column", default=LABEL_COLUMN)
    parser.add_argument("--train-fraction", type=float, default=0.7)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out-dir", type=Path, default=Path("evals/results"))
    args = parser.parse_args(argv)

    clean = clean_gnss(load_recordings(args.data, args.label_column))
    result = compare_models(clean, train_fraction=args.train_fraction, seed=args.seed)
    result["generated_utc"] = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
    result["environment"] = {
        "python": platform.python_version(),
        "scikit_learn": sklearn.__version__,
        "xgboost": xgboost.__version__,
        "pandas": pd.__version__,
        "numpy": np.__version__,
    }

    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "compare.json").write_text(json.dumps(result, indent=2) + "\n")
    (args.out_dir / "COMPARE.md").write_text(render(result, [p.name for p in args.data]))
    print(f"Wrote {args.out_dir / 'COMPARE.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
